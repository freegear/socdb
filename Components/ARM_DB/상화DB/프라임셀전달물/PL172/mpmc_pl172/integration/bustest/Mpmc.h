#define ZERO        0x00000000
#define NoMask      0xFFFFFFFF
#define MaskAll     0x00000000
/******************************************************************************/
/********************** GENERAL VARIABLE DECLARATION **************************/
/******************************************************************************/
#define MPMC_BASE        0x50000000
#define GS_BASE          0x40000000


/******************************************************************************/
/******************************************************************************/
/************************** GENERIC SLAVE REGISTERS ***************************/
/******************************************************************************/
/******************************************************************************/
/***     Generic slave is used to give all types of responses to the        ***/
/***     transactions initiated by TIC master.                              ***/

#define GS_ARRAY1        (GS_BASE + 0x100)
#define GS_ARRAY2        (GS_BASE + 0x500)
#define GS_WCS1          (GS_BASE + 0x000)
#define GS_WCS2          (GS_BASE + 0x004)
#define GS_CR            (GS_BASE + 0x008)
#define GS_TMOUT         (GS_BASE + 0x00C)
#define GS_XRDLY         (GS_BASE + 0x010)


/******************************************************************************/
/******************************************************************************/
/********************************** MPMC **************************************/
/******************************************************************************/
/******************************************************************************/



/******************************************************************************/
/******************* MPMC Integration Test Support Registers ******************/
/******************************************************************************/
/* ---------------------------------------------------------------------------*/
/* The Offset values are from the MPMC register base address.                 */
/* ---------------------------------------------------------------------------*/
/******************************************************************************/
/*============================================================================*/
/* Register                 Offset                R/W              Size       */
/*============================================================================*/
/* MPMCITCR                 0xF00                R/W                 0        */
/* MPMCITIP                 0xF20                R/W                 0        */
/* MPMCITOP                 0xF40                R/W                 0        */
/******************************************************************************/
#define MPMCITCR                 (MPMC_BASE + 0xF00)
#define MPMCITIP                 (MPMC_BASE + 0xF20)
#define MPMCITOP                 (MPMC_BASE + 0xF40)
/******************************************************************************/

/******************************************************************************/
/************************** REGISTER MASK VALUES ******************************/
/******************************************************************************/

#define MASK_MPMCITIP            0x000003FF
#define MASK_MPMCITOP            0x00000003

