// -----------------------------------------------------------------------------
// Grey Scaler Main Function
// -----------------------------------------------------------------------------
function [5:0] GreyScaler;

input [17:0] UpColor;
input [17:0] LpColor;

begin

// -----------------------------------------------------------------------------
// Load and Increment Control Signal Generation : Line & Pixel Counters
// -----------------------------------------------------------------------------
  if (StartDis)
    begin
      // At the start of display after reset
      PixelCount = 16 * (PPL + 1) - 1;
      LineCount  = LPP;
    end
  else
    begin
      // Decrement Pixel and Line Counter
      if (!PixelCount)
        begin
          if (!LineCount)
            LineCount = LPP;
          else
            LineCount = LineCount - 1'b1;
          PixelCount = 16 * (PPL + 1) - 1;
        end
      else
        PixelCount = PixelCount - 1'b1;
    end

// -----------------------------------------------------------------------------
// Frame Phase Accumulator Update
// -----------------------------------------------------------------------------
  if (StartDis)
    begin
      // At the beginning of display
      fp2 =  1'b0;
      fp5 =  3'b000;
      fp9 =  4'b0000;
      fp15 = 4'b1111;
      trp2 =  1'b0;
      trp5 =  3'b000;
      trp9 =  4'b0000;
      trp15 = 4'b1111;
    end
  else if (!LineCount && !PixelCount) 
    begin
      //  At End of a Frame increment frame counters
      fp2  = ~ fp2;
      fp5  = IncFrame5(fp5);
      fp9  = IncFrame9(fp9);
      fp15 = IncFrame15(fp15);
      trp2 = urp2;
      trp5 = urp5;
      trp9 = urp9;
      trp15 = urp15;
    end
  
// -----------------------------------------------------------------------------
// Row Phase Accumulator Update
// -----------------------------------------------------------------------------
  if (StartDis || !LineCount && !PixelCount)
    begin
      //  Load row values at the end of frame
      urp2  = fp2;
      urp5  = fp5;
      urp9  = fp9;
      urp15 = fp15;
      lrp2 = trp2;
      lrp5 = trp5;
      lrp9 = trp9;
      lrp15 = trp15;
    end
  else if (PixelCount == 1)
    begin
      // Increment Row Conters at the end of each row
      urp2  = ~ urp2;
      urp5  = IncRow5 (urp5);
      urp9  = IncRow9 (urp9);
      urp15 = IncRow15 (urp15);
      lrp2  = ~ lrp2;
      lrp5  = IncRow5 (lrp5);
      lrp9  = IncRow9 (lrp9);
      lrp15 = IncRow15 (lrp15);
    end

// -----------------------------------------------------------------------------
// Column Phase Accumulator Update
// -----------------------------------------------------------------------------
    if (StartDis || (PixelCount== (16 * (PPL + 1) - 1)))
    begin
      //  Load column values
      ucp2  = urp2;
      ucp5  = urp5;
      ucp9  = urp9;
      ucp15 = urp15;
      lcp2  = lrp2;
      lcp5  = lrp5;
      lcp9  = lrp9;
      lcp15 = lrp15;
    end
  else
    begin
      //  Increment  column counters
      ucp2  = ~ ucp2;
      ucp5  = IncCol5 (ucp5);
      ucp9  = IncCol9 (ucp9);
      ucp15 = IncCol15 (ucp15);
      lcp2  = ~ lcp2;
      lcp5  = IncCol5 (lcp5);
      lcp9  = IncCol9 (lcp9);
      lcp15 = IncCol15 (lcp15);
    end

// -----------------------------------------------------------------------------
// Make StartDis low:
// -----------------------------------------------------------------------------
  StartDis = 1'b0;

// -----------------------------------------------------------------------------
// Greyscaler Output Generation
// -----------------------------------------------------------------------------

  GreysU = Greyscale (ucp2, ucp5, ucp9, ucp15);
  GreysL = Greyscale (lcp2, lcp5, lcp9, lcp15);

  UpRGS = vidgsmux (UpColor[5:2], GreysU);
  UpGGS = vidgsmux (UpColor[11:8], GreysU);
  UpBGS = vidgsmux (UpColor[17:14], GreysU);
  LpRGS = vidgsmux (LpColor[5:2], GreysL);
  LpGGS = vidgsmux (LpColor[11:8], GreysL);
  LpBGS = vidgsmux (LpColor[17:14], GreysL);

  GreyScaler = {LpRGS, LpGGS, LpBGS, UpRGS, UpGGS, UpBGS};

end
endfunction

