function [13:1]  Greyscale;
 
  input cp2;
  input [2:0] cp5;
  input [3:0] cp9;
  input [3:0] cp15;
   
  //  Define the 16 grey-scales, as a function of the outputs of the column
  //  phase accumulators
  reg [13:1] Result;
begin
  Result[1] = cp9[1] & cp9[0];
  Result[2] = cp5[2];
  Result[3] = cp15[3] & cp15[0];
  Result[4] = ~ (cp9[1] | cp9[0]);
  Result[5] = cp5[0];
  Result[6] = cp9[3];
  Result[7] = cp2;
  Result[8] = ~ Result[6];
  Result[9] = ~ Result[5];
  Result[10] = ~ Result[4];
  Result[11] = ~ Result[3];
  Result[12] = ~ Result[2];
  Result[13] = ~ Result[1];
  Greyscale =  Result;
end
endfunction
 
