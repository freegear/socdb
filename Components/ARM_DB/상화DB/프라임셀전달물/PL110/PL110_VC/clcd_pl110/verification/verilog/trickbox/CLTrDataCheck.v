module CLTrDataCheck(
                     HCLK,
                     VSYNCState,
                     CLCLK,
                     HRESETN,
                     CLTrEn,
                     CLTrIntrTest,
                     CLTrFUFIntrTst,
                     CLPOWER,
                     DataAvail,
                     Check,
                     DataIn,
                     PPL,
                     LPP,
                     CLD,
                     BPP,
                     BW,
                     TFT,
                     Mono8,
                     Dual,
                     BGR,
                     BEBO,
                     BEPO,
                     CLTrPanel,
                     ResetWritePtrs,

                     // Palette RAM Signals
                     PalSelect,
                     PalWrite,
                     PalData,
                     PalAddr
                     );

input         HCLK; 
// Clock


input [2:0]   VSYNCState;
// Vertical Sync input from protocol check
input         CLCLK; 
// CLCD Clock

input         HRESETN;
// Asynchronous Reset (active low)

input         CLTrEn;
// CLCD Trickbox Enable

input         CLTrIntrTest;
// CLCD Trickbox interupt test  bit

input         CLTrFUFIntrTst;
// CLCD Trickbox FIFO underflow interupt test  bit

input         CLPOWER;
// Panel Power

input         DataAvail;
// FIFO Write Signal = HREADY && HTRANS[1]   : from CLCDIf Module

input         Check;
// FIFO Read Clock = CLCP in Active Region   : from CLCDProtCheck Module

input [31:0]  DataIn;
// Data Input from Data Generator

input [5:0]      PPL;
// Pixel Per Line

input [9:0]      LPP;
// Line Per Panel

input [23:0]  CLD;
// Data Input from CLCD Panel Port

input [2:0]   BPP;
// Bits per pixel
// --------------
// Value   BPP
// ---------------
//  000 :  1 bpp
//  001 :  2 bpp
//  010 :  4 bpp
//  011 :  8 bpp
//  100 : 16 bpp
//  101 : Reserved
//  110 : Reserved
//  111 : Reserved

input         BW;
// Black-White mode in STN

input         TFT;
// Indicates TFT or STN Mode

input         Mono8;
// Indicates MONO 8 bit or 4 bit mode

input         Dual;
// Indicates Single or Dual Panel STN mode

input         BGR;
// Indicates BGR or RGB format

input         BEBO;
// Indicates Big Endian or Little Endian Byte order

input         BEPO;
// Indicates Big Endian or Little Endian Pixel ordering within a byte
// Valid for 1, 2 and 4 BPP Mode. In Code 8 BPP mode is included in it for
// Code reduction.

input         CLTrPanel;
// Indicates Lower or Upper Panel Data transaction in STN Dual Panel mode
// Value  :  Indicates
// ------------------------------
//   0    : Upper / Default Panel
//   1    : lower           Panel

input         ResetWritePtrs;
// Indicates initilisation of the write pointers

// Palette Signals
// ---------------

input         PalSelect;
// Palette Select Signal : generated by decoding iHADDR with enable as
// iHSEL && iHREADYin && iHTRANS[1]

input         PalWrite;
// Write Signal : iHWRITE && iHSELCom from CLTrAHBIf

input [31:0]  PalData;
// Palette Data to write : HWDATA from CLTrAHBIf

input [6:0]   PalAddr;
// Palette Address : iHADDR[8:2] from CLTrAHBIf

// -----------------------------------------------------------------------------
//
//                             CLTrDataCheck
//                             =============
//
// -----------------------------------------------------------------------------
//
// Overview
// ========
// This module is intended for CLCD Panel Data Check for all the TFT and STN 
// modes. This module includes:
// - Palette RAM Write Block
// - FIFO Write Block for Upper and Lower Panel
// - Fill Level  Write Block for Upper and Lower Panel
// - Data Read and Check Block
// - Data Check Task and data dump
//
// Note: Two variable `define s are there:
// ----  o EXIT  : Indicates what to do on ERROR : Exit or Continue
//       o IMAGE : Indicates Image or random testing
// -----------------------------------------------------------------------------
 
// -----------------------------------------------------------------------------
// Constant declarations
// -----------------------------------------------------------------------------
// BPP Value
// ---------
`define BPP1             3'b000
`define BPP16            3'b100
`define BPP24            3'b101

// What to do on ERROR : Exit or Continue
// --------------------------------------
`ifdef EXIT
  `define ERR_EXIT   $finish
`else
  `define ERR_EXIT   $display("Error Exit\n")
`endif
 
// -----------------------------------------------------------------------------
// Wire declarations
// -----------------------------------------------------------------------------
wire          HCLK;              // (module input)
wire          CLCLK;             // (module input)
wire          HRESETN;           // (module input)
wire          CLTrEn;            // (module input)
wire          CLTrIntrTest;      // (module input)
wire          CLTrFUFIntrTst;    // (module input)
wire          CLPOWER;           // (module input)
wire          DataAvail;         // (module input)
wire          Check;             // (module input)
wire  [31:0]  DataIn;            // (module input)
wire  [5:0]   PPL;               // (module input)
wire  [9:0]   LPP;               // (module input)
wire  [23:0]  CLD;               // (module input)
wire  [2:0]   BPP;               // (module input)
wire          BW;                // (module input)
wire          TFT;               // (module input)
wire          Mono8;             // (module input)
wire          Dual;              // (module input)
wire          BGR;               // (module input)
wire          BEBO;              // (module input)  
wire          BEPO;              // (module input)
wire          CLTrPanel;         // (module input)
wire          PalWrite;          // (module input)
wire  [31:0]  PalData;           // (module input)
wire  [6:0]   PalAddr;           // (module input)
wire          ResetWritePtrs;    // (module input)

// -----------------------------------------------------------------------------
// Register declarations
// -----------------------------------------------------------------------------
reg [31:0]                Palette[127:0];
// Palette Memory

reg [31:0]                FIFO[393215:0];
// FIFO Memory

reg [31:0]                FIFO1[393215:0];
// Another FIFO Memory for Dual mode 

reg [18:0]                 RdPtr;
// Read Pointer for FIFO

reg [18:0]                 WrPtr;
// Write Pointer for FIFO
 
reg [18:0]                 Filllevel;
// FIFO Fill Level

reg [18:0]                 RdPtr1;
// Read Pointer for FIFO1
 
reg [18:0]                 WrPtr1;
// Write PPointer for FIFO1


//  Fill levels indicates that there should not be difference of
//  of more than 256  words in Read and Write pointers
reg [18:0]                 Filllevel1;
// FIFO1 Fill Level

reg [7:0]                 Index;
// Index to Palette RAM from FIFO

reg [7:0]                 Index1;
// Index to Palette RAM from FIFO1

reg [31:0]                Temp32;
// Temporary Register of 32 bit width to hold the data from FIFO

reg [31:0]                Temp321;
// Temporary Register of 32 bit width to hold the data from FIFO1

reg [15:0]                Phy16;
// Physical Image Data (BGR Value with Bright bit) from Palette or FIFO (16 bpp)

reg [23:0]                Phy24;
// Physical Image Data in 24 bpp TFT mode

reg [15:0]                Phy161;
// Physical Image Data (BGR Value with Bright bit) from Palette or FIFO1(16 bpp)

reg [17:0]                Phy18;
// Expected CLD[23:0] for TFT mode : Input to Grey Scalar for STN mode

reg [17:0]                Phy181;
// Input to Grey Scalar for STN Dual mode 

reg [17:0]                PhyGS18;
// Expected CLD[23:0] for STN mode

reg [5:0]                 GS6;
// Output of Grey Scalar

reg [7:0]                 Temp8;
// Temporary Register of 8 bit width to hold bytes extracted from Temp32

reg [7:0]                 Temp81;
// Temporary Register of 8 bit width to hold bytes extracted from Temp321

reg [3:0]                 BPPValue;
// Actual BPP Value i.e. 2 E+BPP

reg [2:0]                 Bitpos;
// Bit position variable in Output Formater in STN mode

reg                       StartDis;
// To be used in Grey Scaler : 
// Whenever HRESETN comes, this bit becomes high
// In Data_Check task will be set to low

reg [2:0]                Cld_loop;
// To read the data twice in 16 bpp STN mode

integer                   i;
// Count Variable i

integer                   j;
// Count Variable j

integer                   k;
// Count Variable k

integer                   n;
// Count Variable n

integer                   m;
// Count Variable m


integer                   Previous;
// Count Variable Previous value of n

integer                   ImageFile;
// Image File Handler : For data dump


// -----------------------------------------------------------------------------
// Main body of code
// =================
// -----------------------------------------------------------------------------

// -----------------------------------------------------------------------------
// File Initiation for Data Dumping
// -----------------------------------------------------------------------------
`ifdef IMAGE
initial
begin : File_Ini
  ImageFile = $fopen("Output.dat");
end
`endif

// -----------------------------------------------------------------------------
// Palette RAM Write Block
// -----------------------------------------------------------------------------
always @(posedge HCLK)
begin : p_PaletteWrite
  if (PalSelect && PalWrite)
    begin
      // Each write will update two successive Palette entries
      Palette[PalAddr] <= PalData[31:0];
    end
end

// -----------------------------------------------------------------------------
//  Initialising the write pointers at each edge of Vsync pulse 
// -----------------------------------------------------------------------------
always @( negedge HCLK)
begin : p_Reset_Ptrs
  if(ResetWritePtrs)
    begin
      WrPtr  = 19'b0;
      WrPtr1  = 19'b0;
      Filllevel = 19'b0;
      Filllevel1 = 19'b0;
    end
end
// -----------------------------------------------------------------------------
// FIFO Write Block : Write will happen at each HCLK whenever DataAvail is high
// -----------------------------------------------------------------------------
always @(negedge HCLK or negedge HRESETN or negedge CLTrEn )
begin : p_FIFOWrite
  if (!HRESETN || !CLTrEn )
    WrPtr  = 19'b0;
  // FIFO Write for Upper Panel for which CLTrPanel = 0
  else if (DataAvail && !CLTrPanel)
    begin
      // If FIFO is Full
      if (Filllevel == 393215)
        begin
          $display($time," : ERROR : CLCD Input without Output\n");
          `ERR_EXIT;
        end
      else
        begin
          FIFO[WrPtr] = DataIn;
          WrPtr = WrPtr + 1'b1;
        end
    end
end

// -----------------------------------------------------------------------------
// Filllevel Generation Block : Fill-level value denotes the number of elements
// in the FIFO.
// -----------------------------------------------------------------------------
always @(posedge HCLK or posedge Check or negedge HRESETN or negedge CLTrEn)
begin : p_GenFilllevel
  if (!HRESETN || !CLTrEn)
    Filllevel = 19'b0;
  // Increment Fill-level value in Write cycle
  else if (DataAvail && Filllevel != 393215 && !CLTrPanel)
    Filllevel = Filllevel + 1'b1;
end
 
// -----------------------------------------------------------------------------
// FIFO1 Write Block : Write will happen at each HCLK whenever DataAvail is high
// and in STN Dual Panel Mode
// -----------------------------------------------------------------------------
always @(negedge HCLK or negedge HRESETN or negedge CLTrEn)
begin : p_FIFO1Write
  if (!HRESETN || !CLTrEn)
    WrPtr1 = 19'b0;
  // FIFO Write to Lower Panel FIFO in Dual panel STN mode
  else if (DataAvail && !TFT && Dual && CLTrPanel)
    begin
      if (Filllevel1 == 393215)
        begin
          $display($time," : ERROR : CLCD Input without Output\n");
          `ERR_EXIT;
        end
      else
        begin
          FIFO1[WrPtr1] = DataIn;
          WrPtr1 = WrPtr1 + 1'b1;
        end
    end
end

// -----------------------------------------------------------------------------
// Filllevel Generation Block for FIFO1 in STN Dual Panel mode
// -----------------------------------------------------------------------------
always @(posedge HCLK or posedge Check or negedge HRESETN or negedge CLTrEn)
begin : p_GenFilllevel1
  if (!HRESETN || !CLTrEn)
    Filllevel1 = 19'b0;
  else if (DataAvail && Filllevel1 != 393215  && !TFT && Dual && CLTrPanel)
    Filllevel1 = Filllevel1 + 1'b1;
  // Check if CLTrPanel are high when Dual is low : ERROR in Test
  if (!TFT && !Dual && CLTrPanel)
    begin
      $display($time," : ERROR : CLTrPanel is 1 in STN Single panel mode\n");
     `ERR_EXIT;
    end
end

// -----------------------------------------------------------------------------
// This block initialises the read pointers at the start of the frame
// -----------------------------------------------------------------------------
always @(HRESETN or CLTrEn or VSYNCState)
begin :p_Initialize   
  // Initialize all the variables used in this block
  if (!HRESETN || !CLTrEn || (VSYNCState == 3'b001))
     begin
       RdPtr    = 19'b0;
       RdPtr1    = 19'b0;
       Bitpos   = 3'b111;
       Phy18    = 18'b0;
       PhyGS18  = 18'b0;
     end
end
// -----------------------------------------------------------------------------
// This block generate startdis signal at the start of the frame
// -----------------------------------------------------------------------------
always @(posedge CLTrEn or posedge HRESETN)
begin : p_StartDisplay
    StartDis = 1'b1;
end
// -----------------------------------------------------------------------------
// Data Read and Check Block : This block will read the data from FIFO in a
// continuous manner and process it. Then the data will be checked by invoking
// Data_Check task which will check the data at each CLCP in Active region.
// Note: Check is the version of CLCP in Active Region.
//       Data processing and Error checking for Lower Panel FIFO (FIFO1) will
//       be active only in STN Dual Panel mode i.e. at logic (!TFT && Dual).
// -----------------------------------------------------------------------------
always @ (posedge Check)
begin : p_DataReadNCheck
  Previous = 2;
  if (TFT) Cld_loop = 1;
  else 
    begin
      case (BPP)
        `BPP16 : Cld_loop = 2;
        default: Cld_loop = 1;
      endcase
    end
  // Check is no data  in Upper/Lower Panel FIFO to Read
  if (Filllevel == 19'b0 || !TFT && Dual && Filllevel1 == 19'b0)
    begin
      if(!CLTrFUFIntrTst)
        begin
          $display($time," : ERROR : CLCD GIVING OUTPUT without INPUT\n");
          `ERR_EXIT;
        end
    end
  else 
    begin
      repeat (Cld_loop) 
        begin
          // Read a 32 bit data from Upper Panel FIFO
          Temp32 = FIFO[RdPtr];
          RdPtr = RdPtr + 1'b1;
          Filllevel = Filllevel - 1'b1;
          if (!TFT && Dual)
            begin
              // Read a 32 bit data from Lower Panel FIFO (FIFO1)
              Temp321 = FIFO1[RdPtr1];
              RdPtr1 = RdPtr1 + 1'b1;
              Filllevel1 = Filllevel1 - 1'b1;
            end
          // Data Processing and Checking
          // ============================
          if ((BPP == `BPP24) && TFT)
            begin
             if (BGR == 1)
               begin
                 Phy24 = {Temp32[7:0],Temp32[15:8],Temp32[23:16]};
                 Data_Check(Phy24);
               end
             else
               begin
                 Phy24 = Temp32[23:0];
                 Data_Check(Phy24);
               end
            end
          else if ((BPP == `BPP24) && !TFT)
            $display($time," : ERROR : INVALID BPP SETTING FOR STN MODE\n");
 
          else if (BPP == `BPP16)
            // 16 BPP Mode :  BEPO Value is Insignificant
            // ------------------------------------------
            begin
              // For 1st 16 bit half of 32 bit data
              // ----------------------------------
              if (BEBO)
                // In Big Endian Byte Ordering : 1st data will be the upper half
                begin
                  Phy16 = Temp32[31:16];
                  // In case of STN Dual Panel mode
                  if (!TFT && Dual)
                    Phy161 = Temp321[31:16];
                end
              else
              // In Little Endian Byte Ordering :1st data will be the Upper half
                begin
                  Phy16  = Temp32[15:0];
                  // In case of STN Dual Panel mode
                  if (!TFT && Dual)
                    Phy161  = Temp321[15:0];
                end
              // Formatter : Converts 16 bit Data to actual 18 bit CLD
              // ---------
              // Interchange the R and B for BGR mode and also place the bright 
              // bit as the LSB of each R, G, B field.
              if (BGR)
                // R and B interchange is needed.
                begin
                  Phy18 = {Phy16[4:0],Phy16[15],Phy16[9:5],Phy16[15],
                                     Phy16[14:10],Phy16[15]};
                  Phy181 = 0; 
                  if (!TFT && Dual)
                    Phy181 = {Phy161[4:0],Phy161[15],Phy161[9:5],Phy161[15],
                                       Phy161[14:10],Phy161[15]};
                end
              else
                // R and B interchange is not needed.
                begin
                  Phy18 = {Phy16[14:10],Phy16[15],Phy16[9:5],Phy16[15],
                                       Phy16[4:0],Phy16[15]};
                  Phy181 = 0;
                  if (!TFT && Dual)
                    Phy181 = {Phy161[14:10],Phy161[15],Phy161[9:5],Phy161[15],
                                       Phy161[4:0],Phy161[15]};
                end
              if (TFT)
                // For TFT 16 Bpp mode Palette is not required.
                Data_Check({6'b0,Phy18});
              else
                // STN mode
                begin
                  GS6 = GreyScaler(Phy18,Phy181);
                  // GS6[2:0] = [RGS,GGS,BGS] for Upper Panel
                  // GS6[5:3] = [RGS,GGS,BGS] for Lower Panel
                  if (BW)
                    // For MONO mode of STN
                    begin
                      if (Mono8)
                        m = 8;
                      else
                        m = 4;
                      PhyGS18[Bitpos % m] = GS6[2];
                      if (Dual)
                        PhyGS18[8 + Bitpos % m] = GS6[5];
                      else
                        PhyGS18[8 + Bitpos % m] = 1'b0;
                      // 1st Pixel will correspond to MSB
                      // When one data is ready Check it
                      if (Bitpos % m == 0)
                        Data_Check({6'b0,PhyGS18});
                      Bitpos = Bitpos - 1'b1;
                    end
                  else
                    // For COLOR mode of STN
                    begin
                      n = Previous;
                      while( n >= 0)
                        begin
                          PhyGS18[Bitpos] = GS6[n];
                          if (Dual)
                            PhyGS18[8 + Bitpos] = GS6[3 + n];
                          if(n != 0)
                            Previous = n -1;
                          else 
                            Previous = 2;
                          n = n - 1;
                          if (Bitpos == 0)
                              Data_Check({6'b0,PhyGS18});
                          Bitpos = Bitpos - 1'b1;
                        end
                    end
                end
  
              // For 2nd 16 bit half of 32 bit data
              // ----------------------------------
              if (BEBO)
                // In Big Endian Byte Ordering : 1st data will be the upper half
                begin
                  Phy16  = Temp32[15:0];
                  if (!TFT && Dual)
                    Phy161  = Temp321[15:0];
                end
              else
              // In Little Endian Byte Ordering :1st data will be the Upper half
                begin
                  Phy16 = Temp32[31:16];
                  if (!TFT && Dual)
                    Phy161 = Temp321[31:16];
                end
              // BGR and Bright bit consideration to form the 18 bit CLD
              if (BGR)
                begin
                  Phy18 = {Phy16[4:0],Phy16[15],Phy16[9:5],Phy16[15],
                                     Phy16[14:10],Phy16[15]};
                  Phy181 = 0;
                  if (!TFT && Dual)
                    Phy181 = {Phy161[4:0],Phy161[15],Phy161[9:5],Phy161[15],
                                   Phy161[14:10],Phy161[15]};
                end
              else
                begin
                  Phy18 = {Phy16[14:10],Phy16[15],Phy16[9:5],Phy16[15],
                                       Phy16[4:0],Phy16[15]};
                  Phy181 = 0;
                  if (!TFT && Dual)
                    Phy181 = {Phy161[14:10],Phy161[15],Phy161[9:5],Phy161[15],
                                         Phy161[4:0],Phy161[15]};
                end
    
              if (TFT)
                // For TFT mode
                Data_Check({6'b0,Phy18});
              else
                // For STN mode
                begin
                  GS6 = GreyScaler(Phy18,Phy181);
                  // GS6[2:0] = [RGS,GGS,BGS] for Upper Panel
                  // GS6[5:3] = [RGS,GGS,BGS] for Lower Panel
                  if (BW)
                    // MONO STN mode
                    begin
                      if (Mono8)
                        m = 8;
                      else
                        m = 4;
                      PhyGS18[Bitpos % m] = GS6[2];
                      if (Dual)
                        PhyGS18[8 + Bitpos % m] = GS6[5];
                      else
                        PhyGS18[8 + Bitpos % m] = 1'b0;
                      if(Bitpos % m == 0)
                        Data_Check({6'b0,PhyGS18});
                      Bitpos = Bitpos - 1'b1;
                    end
                  else
                    // COLOR STN mode
                    begin
                      n = Previous;
                      while( n >= 0)
                        begin
                          PhyGS18[Bitpos] = GS6[n];
                          if (Dual)
                             PhyGS18[8 + Bitpos] = GS6[3 + n];
                          if(n != 0)
                             Previous = n - 1;
                          else 
                             Previous = 2;
                          n = n - 1;  
                          if (Bitpos == 0)
                            begin
                             Data_Check({6'b0,PhyGS18});
                            end
                          Bitpos = Bitpos - 1'b1;
                        end
                    end
                end
            end
          else
     
            // 1,2,4 and 8 BPP Modes : BEPO Value is Significant (except 8 BPP)
            // ---------------------------------------------------
            // Extract each byte from 32 bit data depending on BEBO and then
            // extract each pixel from the byte depending on BEPO.
            begin
              for (i = 0; i < 32; i = i + 8)
                begin
                  // Extraction of Bytes from 32 bit data
                  if (BEBO)
                    // Temp8[7:0] = Temp32[32 - i:24 - i]
                    for (k = 0; k < 8; k = k + 1)
                      begin
                        Temp8[k] = Temp32[24 - i + k];
                        if (!TFT && Dual)
                          Temp81[k] = Temp321[24 - i + k];
                      end
                  else
                    // Temp8[7:0] = Temp32[i + 7:i]
                    for (k = 0; k < 8; k = k + 1)
                      begin
                        Temp8[k] = Temp32[i + k];
                        if (!TFT && Dual)
                          Temp81[k] = Temp321[i + k];
                      end
                  // BPPValue = 2 E +BPP;
                  BPPValue = 1 << BPP;
                  // Extraction of Pixels from each byte
                  for (j = 0; j < 8; j = j + BPPValue)
                    begin
                      // Initialize Index values
                      Index  = 8'b0;
                      Index1 = 8'b0;
                      if (BEPO)
                      // Big Endian Pixel Ordering within a Byte
                        if (BPP == `BPP1)
                          // For 1 Bpp mode
                          begin
                            Index[0] = Temp8[7-j];
                            if (!TFT && Dual)
                              Index1[0] = Temp81[7-j];
                          end
                        else
                          // For 2, 4, 8 Bpp mode
                          begin
                            Index = 0;
                            // Index = Temp8[15 - BPPValue - j:8 - BPPValue - j]
                            for (k = 0; k < BPPValue; k = k + 1)
                              begin
                                Index[k] = Temp8[8-BPPValue-j+k];
                                if (!TFT && Dual)
                                  Index1[k] = Temp81[8-BPPValue-j+k];
                              end
                          end
                      // Little Endian Pixel Ordering within a Byte
                      else
                        if (BPP == `BPP1)
                          // For 1 Bpp mode
                          begin
                            Index = Temp8[j];
                            if (!TFT && Dual)
                              Index1 = Temp81[j];
                          end
                        else
                          // For 2, 4, 8 Bpp mode
                          begin
                            for (k = 0; k < BPPValue; k = k + 1)
                              begin
                                Index[k] = Temp8[j+k];
                                if (!TFT && Dual)
                                  Index1[k] = Temp81[j+k];
                              end
                          end
                      // Form the Palette Output
                      if (BEBO) begin
                        Phy16  = Palette[Index [7:1]] >> (16 * (1 - Index[0]));
                        Phy161 = Palette[Index1[7:1]] >> (16 * (1 - Index1[0]));
                      end
                      else begin
                          Phy16  = Palette[Index [7:1]] >> (16 * Index[0]);
                          Phy161 = Palette[Index1[7:1]] >> (16 * Index1[0]);
                      end
                      if (BGR)
                        begin
                          Phy18 = {Phy16[4:0],Phy16[15],Phy16[9:5],Phy16[15],
                                               Phy16[14:10],Phy16[15]};
                          Phy181 = 0;
                          if (!TFT && Dual)
                            Phy181 = {Phy161[4:0],Phy161[15],Phy161[9:5],
                                      Phy161[15],Phy161[14:10],Phy161[15]};
                        end
                      else
                        begin
                          Phy18 = {Phy16[14:10],Phy16[15],Phy16[9:5],Phy16[15],
                                               Phy16[4:0],Phy16[15]};
                          Phy181 = 0;
                          if (!TFT && Dual)
                            Phy181 = {Phy161[14:10],Phy161[15],Phy161[9:5],
                                      Phy161[15], Phy161[4:0],Phy161[15]};
                        end
                      if (TFT)
                        // For TFT mode
                        Data_Check({6'b0,Phy18});
                      else
                        // For STN mode
                        begin
                          GS6 = GreyScaler(Phy18,Phy181);
                          // GS6[2:0] = [RGS,GGS,BGS] for Upper Panel
                          // GS6[5:3] = [RGS,GGS,BGS] for Lower Panel
                          if (BW)
                            // MONO STN mode
                            begin
                              if (Mono8)
                                m = 8;
                              else
                                m = 4;
                              PhyGS18[Bitpos % m] = GS6[2];
                              if (Dual)
                                PhyGS18[8 + Bitpos % m] = GS6[5];
                              else
                                PhyGS18[8 + Bitpos % m] = 1'b0;
                              if (Bitpos % m == 0)
                                 // Check when data becomes avaiable
                                 Data_Check({6'b0,PhyGS18});
                              Bitpos = Bitpos - 1'b1;
                            end
                          else
                            // COLOR STN mode
                            begin
                            n = Previous;
                            while( n >= 0)
                              begin
                                PhyGS18[Bitpos] = GS6[n];
                                if (Dual)
                                  PhyGS18[8 + Bitpos] = GS6[3 + n];
                                if(n != 0)
                                  Previous = n -1;
                                else
                                  Previous = 2;
                                n = n - 1;
                                if (Bitpos == 0)
                                  begin
                                    Data_Check({6'b0,PhyGS18});
                                  end
                                Bitpos = Bitpos - 1'b1;
                              end
                            end
                        end
                    end   
                end
            end
        end 
    end
end
      
// -----------------------------------------------------------------------------
// Data Check Block (Task) : Checking will wait for a CLCP to arrive in Active
// region and then check. Simultaneously, for actual image data this block will 
// write the formatted Panel data to a file.
// -----------------------------------------------------------------------------
task Data_Check;
input [23:0]  CLTrData;
begin
  if (CLTrEn)
    if(VSYNCState == 3'b011)
      begin
        // Check signal denotes new CLD data  valid, or CLCP had arrived in the
        // Active Region. In the DtatCheck module  data will be checked on the
        // negetive edge of Chcek. The generation of Check is shown below:
        //                  __    __    __    __    __    __    __    __
        //  CLCLK     :  __1  |__1  |__1  |__1  |__1  |__1  |__1  |__1  |__
        //                        ___________             ___________
        //  CLCP      :  ________|           |___________|           |_____
        //               _________ _______________________ ________________
        //  CLD       :  ___D(i)__X__________D(i+1)_______X______D(i+2)____
        //                        _____                   _____
        //  Check     :  ________1     Y_________________|     Y___________
        //                      /|\    ^                       ^
        //                     |     ^ = Data will be checked at these NegEdges.
        //                       |---- = Data can be checked here, otherwise it
        //                                 it will compare D(i) with 
        //                                 "Expected D(i+1)".
            @ (negedge Check or negedge CLTrEn or posedge VSYNCState[2]);
            if (CLD !== CLTrData)
              begin
                if(CLTrEn && VSYNCState == 3'b011 )
                  begin
                    $display($time," ERROR:CLCD Panel Data is not matching \n");
                    `ERR_EXIT;
                  end    
              end
            `ifdef IMAGE
              // Writing the formatted data in a file
              $fdisplay(ImageFile,"%b",CLD);
            `endif
      end
end
endtask

