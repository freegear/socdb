function ROTRIGHT (arg: std_logic_vector; count: integer) 
                   return std_logic_vector is
    constant arg_l: integer := arg'LENGTH - 1;
    alias xarg: std_logic_vector(arg_l downto 0) is arg;
    variable result32: std_logic_vector(arg_l downto 0) := xarg;
    variable result: std_logic_vector(15 downto 0) := xarg(15 downto 0);
    variable countm: integer;
  begin
    countm := count mod (arg_l + 1);
    if countm /= 0 then
      result32(arg_l-countm downto 0) := xarg(arg_l downto countm);
      result32(arg_l downto arg_l-countm+1) := xarg(countm-1 downto 0);
    end if;
    result := result32(15 downto 0);
    return result;
end ROTRIGHT; 

