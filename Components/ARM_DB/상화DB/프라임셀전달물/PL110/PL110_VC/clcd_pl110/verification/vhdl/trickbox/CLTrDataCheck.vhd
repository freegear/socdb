-- The assigning the diference in read and write pointers to the fill levels
-- -----------------------------------------------------------------------------
p_WrapComb : process (HCLK, HRESETN, CLTrEn, DataAvail, Check, ResetWritePtrs)
begin
  if (HRESETN = '0'  or CLTrEn = '0' or ResetWritePtrs = '1') then
    Wrap  <= '0';
  elsif(WrPtr = "11111111" and DataAvail = '1' and CLTrPanel = '0') then
    Wrap  <= '1';  
  elsif(RdPtr = "11111111" and Check = '1') then
    Wrap  <= '0'; 
  end if;
end process p_WrapComb;
