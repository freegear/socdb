-- -----------------------------------------------------------------------------
-- FIFO Write Block : Write will happen at each HCLK whenever DataAvail is high
-- -----------------------------------------------------------------------------
p_FIFOWrite : process (HCLK, HRESETn, CLTrEn) 
variable printstr  : string(1 to 255);
begin
  if ((HRESETn'event and HRESETn = '0') or (HCLK'event and HCLK = '0' and
       ResetWritePtrs = '1') or (CLTrEn'event and CLTrEn = '0')) then
    WrPtr  <= (others => '0');
  -- FIFO Write for Upper Panel for which CLTrPanel = 0
  elsif (HCLK'event and HCLK = '0' and DataAvail = '1' and CLTrPanel = '0') then
    -- If FIFO is Full
    if (Filllevel = 255) then
      -- $display($time," : ERROR : CLCD Input without Output\n");
      fprint(printstr, "ERROR : CLCD Input without Output\n");
        assert false
        report printstr
        severity error;
      if (ERR_EXIT = '0') then
        fprint(printstr, "Error Exit");
        assert false
        report printstr
        severity error;
      else
        assert false
        report printstr
        severity failure;
      end if;
    else 
      FIFO(to_integer(WrPtr)) <= DataIn;
      WrPtr       <= (WrPtr) + '1';
    end if;
  end if;
end process p_FIFOWrite;
-- -----------------------------------------------------------------------------
-- FIFO1 Write Block : Write will happen at each HCLK whenever DataAvail is high
-- and in STN Dual Panel Mode
-- -----------------------------------------------------------------------------
p_FIFO1Write : process (HCLK, HRESETn, CLTrEn) 
variable printstr  : string(1 to 255);
