    Bitpos   := "111";
    Phy18    := (others => '0'); 
    IntPhy18 <= Phy18;
    PhyGS18  := (others => '0');
  elsif (Check = '1') then
    Previous := 2;
    if (TFT = '1') then
      CldLoop := "001";
    else 
      case BPP is
        when BPP16  => CldLoop := "010";
        when others => CldLoop := "001";
      end case;
    end if;
 
    -- Check is no data  in Upper/Lower Panel FIFO to Read
    if (Filllevel = "000000000" or (TFT = '0' and Dual = '1' 
        and Filllevel1 = "000000000")) then
      fprint(printstr, "ERROR : CLCD GIVING OUTPUT without INPUT\n");
      assert (CLTrFUFIntrTst /= '0')
