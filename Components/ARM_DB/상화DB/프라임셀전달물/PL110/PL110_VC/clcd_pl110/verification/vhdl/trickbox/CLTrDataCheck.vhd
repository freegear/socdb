function Greyscale (
                    cp2  : in std_logic;
                    cp5  : in std_logic_vector(2 downto 0);
                    cp9  : in std_logic_vector(3 downto 0);
                    cp15 : in std_logic_vector(3 downto 0)
                   ) return std_logic_vector is
 
  --  Define the 16 grey-scales, as a function of the outputs of the column
  --  phase accumulators
variable Result : std_logic_vector(13 downto 1);
begin
  Result(1)  := cp9(1) and cp9(0);
  Result(2)  := cp5(2);
  Result(3)  := cp15(3) and cp15(0);
  Result(4)  := not (cp9(1) or cp9(0));
  Result(5)  := cp5(0);
  Result(6)  := cp9(3);
  Result(7)  := cp2;
  Result(8)  := not(Result(6));
  Result(9)  := not(Result(5));
  Result(10) := not(Result(4));
  Result(11) := not(Result(3));
  Result(12) := not(Result(2));
  Result(13) := not(Result(1));
return Result;
end Greyscale;
 
