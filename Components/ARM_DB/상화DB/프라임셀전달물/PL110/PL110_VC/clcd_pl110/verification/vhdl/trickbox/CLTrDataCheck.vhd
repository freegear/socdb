  if ((HRESETn'event and HRESETn = '0') or (HCLK'event and HCLK = '0' and 
       ResetWritePtrs = '1') or (CLTrEn'event and CLTrEn = '0')) then
    WrPtr1 <= (others => '0');
  -- FIFO Write to Lower Panel FIFO in Dual panel STN mode
  elsif (((HCLK'event and HCLK = '0') or (CLTrEn'event and CLTrEn = '0')) and 
           DataAvail = '1' and TFT = '0' and Dual = '1' and CLTrPanel = '1')then
    if (Filllevel1 = 255) then
      -- $display($time," : ERROR : CLCD Input without Output\n");
      fprint(printstr, "ERROR : CLCD Input without Output\n");
        assert false
        report printstr
        severity error;
      if (ERR_EXIT = '0') then
        fprint(printstr, "Error Exit");
        assert false
        report printstr
        severity error;
      else
        assert false
        report printstr
        severity failure;
      end if;
    else
      FIFO1(to_integer(WrPtr1)) <= DataIn;
      WrPtr1 <= (WrPtr1) + '1';
    end if;
  end if;
end process p_FIFO1Write;

