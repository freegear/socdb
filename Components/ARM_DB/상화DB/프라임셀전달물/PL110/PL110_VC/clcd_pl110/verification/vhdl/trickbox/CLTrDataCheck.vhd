-- Counters
variable LineCountout  : integer;
variable PixelCountout : integer;
variable iRdPtr        : std_logic_vector(7 downto 0) := (others => '0');
variable iRdPtr1       : std_logic_vector(7 downto 0) := (others => '0');
begin
  if (HRESETn = '0' or CLTrEn = '0' or (VSYNCState = "001")) then
