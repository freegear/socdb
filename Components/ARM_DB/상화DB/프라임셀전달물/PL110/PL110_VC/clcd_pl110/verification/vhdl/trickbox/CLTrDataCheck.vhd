variable UpGGS         : std_logic;
variable UpBGS         : std_logic;
variable LpRGS         : std_logic;
variable LpGGS         : std_logic;
variable LpBGS         : std_logic;

begin

-- -----------------------------------------------------------------------------
-- Load and Increment Control Signal Generation : Line & Pixel Counters
-- -----------------------------------------------------------------------------
  iLineCountout   := LineCountin;
  iPixelCountout  := PixelCountin;
  ifp2out         := fp2in;
  ifp5out         := fp5in;
  ifp9out         := fp9in;
  ifp15out        := fp15in;
  itrp2out        := trp2in;
  itrp5out        := trp5in;
  itrp9out        := trp9in;
  itrp15out       := trp15in;
  iurp2out        := urp2in;
  iurp5out        := urp5in;
  iurp9out        := urp9in;
  iurp15out       := urp15in;
  iucp2out        := ucp2in;
  iucp5out        := ucp5in;
  iucp9out        := ucp9in;
  iucp15out       := ucp15in;
  ilrp2out        := lrp2in;
  ilrp5out        := lrp5in;
  ilrp9out        := lrp9in;
  ilrp15out       := lrp15in;
  ilcp2out        := lcp2in;
  ilcp5out        := lcp5in;
  ilcp9out        := lcp9in;
  ilcp15out       := lcp15in;

  if (StartDis = '1' and ClearDisin = '0') then
    -- At the start of display after reset
    iPixelCountout := (16 * (to_integer(('0' & PPL) + 1))) - 1;
    iLineCountout  := to_integer('0' & LPP);
  else
    -- Decrement Pixel and Line Counter
    if (PixelCountin = 0) then
      if (LineCountin = 0) then
        iLineCountout := to_integer('0' & LPP);
      else
        iLineCountout := LineCountin - 1;
      end if;
      iPixelCountout := 16 * to_integer((('0' & PPL) + 1)) - 1;
    else
      iPixelCountout := PixelCountin - 1;
    end if;
  end if;
-- -----------------------------------------------------------------------------
-- Frame Phase Accumulator Update
-- -----------------------------------------------------------------------------
  if (StartDis = '1' and ClearDisin = '0') then
    ifp2out   := '0';
    ifp5out   := "000";
    ifp9out   := "0000";
    ifp15out  := "1111";
    itrp2out  := '0';
    itrp5out  := "000";
    itrp9out  := "0000";
    itrp15out := "1111";
  elsif (iLineCountout = 0 and iPixelCountout = 0) then 
    --  At End of a Frame increment frame counters
    ifp2out   := not(fp2in);
    ifp5out   := IncFrame5(fp5in);
    ifp9out   := IncFrame9(fp9in);
    ifp15out  := IncFrame15(fp15in);
    itrp2out  := urp2in;
    itrp5out  := urp5in;
    itrp9out  := urp9in;
    itrp15out := urp15in;
  end if;
     
-- -----------------------------------------------------------------------------
-- Row Phase Accumulator Update
-- -----------------------------------------------------------------------------
  if ((StartDis = '1' and ClearDisin = '0') or (iLineCountout = 0 and (iPixelCountout = 0))) then
    --  Load row values at the end of frame
    iurp2out  := ifp2out;
    iurp5out  := ifp5out;
    iurp9out  := ifp9out;
    iurp15out := ifp15out;
    ilrp2out  := itrp2out;
    ilrp5out  := itrp5out;
    ilrp9out  := itrp9out;
    ilrp15out := itrp15out;
  else 
    if (iPixelCountout = 1) then
      -- Increment Row Conters at the end of each row
      iurp2out  := not(urp2in);
      iurp5out  := IncRow5 (urp5in);
      iurp9out  := IncRow9 (urp9in);
      iurp15out := IncRow15 (urp15in);
      ilrp2out  := not(lrp2in);
      ilrp5out  := IncRow5 (lrp5in);
      ilrp9out  := IncRow9 (lrp9in);
      ilrp15out := IncRow15 (lrp15in);
    end if;
  end if;

-- -----------------------------------------------------------------------------
-- Column Phase Accumulator Update
-- -----------------------------------------------------------------------------
    if ((StartDis = '1' and ClearDisin = '0') or 
       (iPixelCountout = (16 * (to_integer(('0' & PPL) + 1)) - 1))) then
      --  Load column values
      iucp2out  := iurp2out;
      iucp5out  := iurp5out;
      iucp9out  := iurp9out;
      iucp15out := iurp15out;
      ilcp2out  := ilrp2out;
      ilcp5out  := ilrp5out;
      ilcp9out  := ilrp9out;
      ilcp15out := ilrp15out;
    else
      --  Increment  column counters
      iucp2out  := not(ucp2in);
      iucp5out  := IncCol5 (ucp5in);
      iucp9out  := IncCol9 (ucp9in);
      iucp15out := IncCol15 (ucp15in);
      ilcp2out  := not(lcp2in);
      ilcp5out  := IncCol5 (lcp5in);
      ilcp9out  := IncCol9 (lcp9in);
      ilcp15out := IncCol15 (lcp15in);
    end if;
-- -----------------------------------------------------------------------------
-- Make StartDis low:
-- -----------------------------------------------------------------------------
  if (StartDis = '1') then
    ClearDis := '1';
  else
    ClearDis := '0';
  end if;
-- -----------------------------------------------------------------------------
-- Greyscaler Output Generation
-- -----------------------------------------------------------------------------
  fp2out        := ifp2out; 
  fp5out        := ifp5out; 
  fp9out        := ifp9out;
  fp15out       := ifp15out;     
  trp2out       := itrp2out ;   
  trp5out       := itrp5out;   
  trp9out       := itrp9out;  
  trp15out      := itrp15out;
  urp2out       := iurp2out  ;
  urp5out       := iurp5out ;
  urp9out       := iurp9out;
  urp15out      := iurp15out ;   
  ucp2out       := iucp2out    ;
  ucp5out       := iucp5out   ;
  ucp9out       := iucp9out ; 
  ucp15out      := iucp15out;
  lrp2out       := ilrp2out;     
  lrp5out       := ilrp5out;    
  lrp9out       := ilrp9out;   
  lrp15out      := ilrp15out; 
  lcp2out       := ilcp2out;   
  lcp5out       := ilcp5out;  
  lcp9out       := ilcp9out; 
  lcp15out      := ilcp15out;
 
  LineCountout  := iLineCountout;  
  PixelCountout := iPixelCountout; 
  
  iGreysU       := Greyscale (iucp2out, iucp5out, iucp9out, iucp15out);
  GreySU        := iGreySU;
  GreysL        := Greyscale (ilcp2out, ilcp5out, ilcp9out, ilcp15out);
  
  UpRGS         := vidgsmux (UpColor(5 downto 2), iGreysU);
  UpGGS         := vidgsmux (UpColor(11 downto 8), iGreysU);
  UpBGS         := vidgsmux (UpColor(17 downto 14), iGreysU);
  LpRGS         := vidgsmux (LpColor(5 downto 2), GreysL);
  LpGGS         := vidgsmux (LpColor(11 downto 8), GreysL);
  LpBGS         := vidgsmux (LpColor(17 downto 14), GreysL);

  GreyScaler    := LpRGS & LpGGS & LpBGS & UpRGS & UpGGS & UpBGS;
end GreyScaler;
-- -----------------------------------------------------------------------------
-- Data Check Block (Task) : Checking will wait for a CLCP to arrive in Active
-- region and then check. Simultaneously, for actual image data this block will
-- write the formatted Panel data to a file.
-- -----------------------------------------------------------------------------
procedure Data_Check (
                      constant CLD       : in std_logic_vector(23 downto 0);
                      constant CLTrData  : in std_logic_vector(23 downto 0)
                     ) is
variable ImageLine  : line;
variable printstr    : string(1 to 255);
begin
  if (CLTrEn = '1') then
    if (VSYNCState = "011") then
      -- Check signal denotes new CLD data is valid, or CLCP had arrived in the
      -- Active Region. In the DtatCheck module the data will be checked on the
      -- negetive edge of Chcek. The generation of Check is shown below:
      --                  __    __    __    __    __    __    __    __
      --  CLCLK     :  __1  |__1  |__1  |__1  |__1  |__1  |__1  |__1  |__
      --                        ___________             ___________
      --  CLCP      :  ________|           |___________|           |_____
      --               _________ _______________________ ________________
      --  CLD       :  ___D(i)__X__________D(i+1)_______X______D(i+2)____
      --                        _____                   _____
      --  Check     :  ________1     Y_________________|     Y___________
      --                      /|\    ^                       ^
      --                       |     ^ = Data will be checked at these NegEdges.
      --                       |------ = Data can be checked here, otherwise it
      --                                 it will compare D(i) with
      --                                 "Expected D(i+1)".
      wait until ((Check'event and Check = '0') or 
                  ( CLTrEn'event and CLTrEn = '0') or
                  (VSYNCState'event and VSYNCState(2) = '1'));
      if (CLD /= CLTrData) then
        if ((CLTrEn = '1') and (VSYNCState = "011")) then
          fprint(printstr, "ERROR:CLCD Panel Data is not matching \n");
          assert false
          report printstr
          severity error;
          if (ERR_EXIT = '0') then
            fprint(printstr, "Error Exit");
            assert false
            report printstr
            severity error;
          else
            assert false
            report printstr
            severity failure;
          end if;
        end if;
      end if;
      wait for 10 ps;
      if (IMAGE = '1') then
        -- Writing the formatted data in a file
        --$fdisplay(ImageFile,"%b",CLD);
        WRITE (ImageLine, to_integer('0' & CLD));
        WRITELINE (ImageFile, ImageLine);
      end if;
    end if;
  end if;
end Data_Check;
 
