  -- Wait for a Check i.e. CLCP to come in Active region
  wait until ((Check'event and Check = '1') or
              (VSYNCState'event and VSYNCState(2) = '1') or
              (VSYNCState'event and VSYNCState = "001"));
  if (VSYNCState(2) = '1' or VSYNCState = "001") then
    iRdPtr   := (others => '0');
    RdPtr    <= iRdPtr;
    RdPtr1   <= (others => '0');
