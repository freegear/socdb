begin

-- -----------------------------------------------------------------------------
-- StartCheck signal is set once the Reset is applied
-- -----------------------------------------------------------------------------
p_ResetOverComb : process (EBICLK, HRESETn, ResetAssrtd)
begin
  if ((ResetAssrtd) and HRESETn = '1') then
    ResetOver <= TRUE;
  end if;
  if (EBICLK'event and EBICLK = '1') then
    if (HRESETn = '0') then
      ResetAssrtd <= TRUE;
    end if;
  end if;
end process p_ResetOverComb;

-- -----------------------------------------------------------------------------
-- Compare the EBIGNT1 and EbiTrGnt1 signals and flag the error message if the
-- the signals are not the same
-- -----------------------------------------------------------------------------
p_CompGnt1Seq : process (EBICLK)
begin
   if ((EBICLK'event and EBICLK = '1') and (ResetOver = TRUE))  then
      if (EBIGNT1 /= EbiTrGnt1) then
         assert FALSE
         report "EBIGNT1 and EbiTrGnt1 signals are different!!"
         severity error;
      end if;
   end if;
end process p_CompGnt1Seq;

-- -----------------------------------------------------------------------------
-- Compare the EBIGNT2 and EbiTrGnt2 signals and flag the error message if the
-- the signals are not the same
-- -----------------------------------------------------------------------------
