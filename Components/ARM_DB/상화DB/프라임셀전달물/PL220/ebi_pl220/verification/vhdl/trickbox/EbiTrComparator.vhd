library IEEE;
use IEEE.std_logic_1164.all;
use IEEE.std_logic_arith.all;

-- -----------------------------------------------------------------------------

entity EbiTrComparator is
  port (
-- Inputs
        EBICLK           : in    std_logic; -- Ebi Clock
        HRESETn          : in    std_logic; -- Bus Reset
        EBIGNT1          : in    std_logic; -- Gnt signal generated by Ebi to
                                            -- Port1
        EBIGNT2          : in    std_logic; -- Gnt signal generated by Ebi to
                                            -- Port2
        EBIGNT3          : in    std_logic; -- Gnt signal generated by Ebi to
                                            -- Port3
        EBIBACKOFF1      : in    std_logic; -- Backoff signal generated Ebi to
                                            -- Port1
        EBIBACKOFF2      : in    std_logic; -- Backoff signal generated Ebi to
                                            -- Port2
        EBIBACKOFF3      : in    std_logic; -- Backoff signal generated Ebi to
                                            -- Port3
        nEBIEXTDATAEN    : in    std_logic_vector(3 downto 0);
                                            -- Data enable signal from Ebi
        EBIEXTADDROUT    : in    std_logic_vector(31 downto 0);
                                            -- Address out from Ebi
        EBIEXTDATAOUT    : in    std_logic_vector(31 downto 0);
                                            -- Data out from Ebi
        EBIDATAIN        : in    std_logic_vector(31 downto 0);
                                            -- Data in from Ebi

        EbiTrGnt1        : in    std_logic; -- Gnt signal generated by trickbox
        EbiTrGnt2        : in    std_logic; -- Gnt signal generated by trickbox
        EbiTrGnt3        : in    std_logic; -- Gnt signal generated by trickbox
        EbiTrBackoff1    : in    std_logic; -- Backoff signal generated by
                                            -- trickbox
        EbiTrBackoff2    : in    std_logic; -- Backoff signal generated by
                                            -- trickbox
        EbiTrBackoff3    : in    std_logic; -- Backoff signal generated by
                                            -- trickbox
        nEbiTrExtDataEn  : in    std_logic_vector(3 downto 0);
                                            -- Data enable signal from trickbox
        EbiTrExtAddrOut  : in    std_logic_vector(31 downto 0);
                                            -- Address out from trickbox
        EbiTrExtDataOut  : in    std_logic_vector(31 downto 0);
                                            -- Data out from trickbox
        EbiTrDataIn      : in    std_logic_vector(31 downto 0)
                                            -- Data in from trickbox

       );
end EbiTrComparator;

