                        EBIGNT1,
                        EBIGNT2,
                        EBIGNT3,
                        EBIBACKOFF1,
                        EBIBACKOFF2,
                        EBIBACKOFF3,
                        nEBIEXTDATAEN,
                        EBIEXTADDROUT,
                        EBIEXTDATAOUT,
                        EBIDATAIN,

                        EbiTrGnt1,
                        EbiTrGnt2,
                        EbiTrGnt3,
                        EbiTrBackoff1,
                        EbiTrBackoff2,
                        EbiTrBackoff3,
                        nEbiTrExtDataEn,
                        EbiTrExtAddrOut,
                        EbiTrExtDataOut,
                        EbiTrDataIn
                       );

// Inputs
input         EBICLK;          // Ebi Clock
input         HRESETn;         // Bus Reset
input         EBIGNT1;         // Gnt signal generated by Ebi to Port1
input         EBIGNT2;         // Gnt signal generated by Ebi to Port2
input         EBIGNT3;         // Gnt signal generated by Ebi to Port3
input         EBIBACKOFF1;     // Backoff signal generated Ebi to
                               // Port1
input         EBIBACKOFF2;     // Backoff signal generated Ebi to
                               // Port2
input         EBIBACKOFF3;     // Backoff signal generated Ebi to
                               // Port3
input   [3:0] nEBIEXTDATAEN;   // Data enable signal from Ebi
input  [31:0] EBIEXTADDROUT;   // Address out from Ebi
input  [31:0] EBIEXTDATAOUT;   // Data out from Ebi
input  [31:0] EBIDATAIN;       // Data in from Ebi

input         EbiTrGnt1;       // Gnt signal generated by trickbox
input         EbiTrGnt2;       // Gnt signal generated by trickbox
input         EbiTrGnt3;       // Gnt signal generated by trickbox
input         EbiTrBackoff1;   // Backoff signal generated by trickbox
input         EbiTrBackoff2;   // Backoff signal generated by trickbox
input         EbiTrBackoff3;   // Backoff signal generated by trickbox
input   [3:0] nEbiTrExtDataEn; // Data enable signal from trickbox
input  [31:0] EbiTrExtAddrOut; // Address out from trickbox
input  [31:0] EbiTrExtDataOut; // Data out from trickbox
input  [31:0] EbiTrDataIn;     // Data in from trickbox

// Inputs
