// -----------------------------------------------------------------------------
// StartCheck signal is set once the Reset is applied
// -----------------------------------------------------------------------------
always @(HRESETn or ResetAssrtd)
begin : p_ResetOverComb
  if ((ResetAssrtd) && HRESETn == 1'b1)
     ResetOver <= `TRUE;
end // p_ResetOverComb

always @(posedge EBICLK)
begin : p_ResetStrComb
  if (HRESETn == 1'b0)
    ResetAssrtd <= `TRUE;
end // p_ResetStrComb

// -----------------------------------------------------------------------------
// Compare the EBIGNT1 and EbiTrGnt1 signals and flag the error message if the
// the signals are not the same
// -----------------------------------------------------------------------------
always @(posedge EBICLK)
begin : p_CompGnt1Seq
  if ((EBICLK == 1'b1) & (ResetOver == `TRUE))
    begin
      if (EBIGNT1 != EbiTrGnt1)
        $display("Error : Time %t : EBIGNT1 and EbiTrGnt1 signals are different!!", $time);
    end
end // p_CompGnt1Seq

