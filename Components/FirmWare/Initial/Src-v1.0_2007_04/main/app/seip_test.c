void InitSEIP()
{
    int i;
    SMT_WRITE(RS_SEIPMUX, 0x03);        // Wave ROM/Internal SRAM Owner : SEIP
    SMT_WRITE( SEIP_ADMCK, 0x80 + 12 ); //ADC MCLK Set *256

    SMT_WRITE(SEIP_RST,0x00000000 ); //SEIP Reset
    delay(10000);
    SMT_WRITE(SEIP_RST,0x00000001 );

    for( i=0; i<315; i++ ){
        CHECK_READY;
        SEIP_WRITE( InitSEIP_Parameter[i][0],InitSEIP_Parameter[i][1] );
    }
}

void NoteOn()
{
	SEIP_WRITE( 0x0020,0x0001 );
}
void NoteOff()
{
	SEIP_WRITE( 0x0020,0x0000 );
}
extern  const unsigned sounddata[];
void PlaySoundData_NotUseDMA()
{
    int i;
    char uart_input;

    for( i=0; i<262120; i++ ){

        while( (SMT_READ(SEIP_RXSTS) & 0x00000200) ){;}
        SMT_WRITE(SEIP_RXDAT, sounddata[i] );
		smt2UARTDataValid(CFG_UART_CH, &uart_input);
		if(uart_input)
        {
            smt2UARTGetCh(CFG_UART_CH, &uart_input, 0);
            if(uart_input == '0')
                break;
        }
    }
}
void Rec_NotUseDMA()
{
	int i;
    char uart_input;
    unsigned int data;
    
    RecCount = 0;
    for( i=0; i<REC_BUFF_SIZE; i++ ){

        while( (SMT_READ(SEIP_TXSTS) & 0x00000100) ){;}
        //DPRINTF("RecData\n");
        
        data = SMT_READ(SEIP_TXDAT);
        RecBuffer[i] = data;
        RecCount = i;
         
		smt2UARTDataValid(CFG_UART_CH, &uart_input);
		if(uart_input)
        {
            smt2UARTGetCh(CFG_UART_CH, &uart_input, 0);
            if(uart_input == '0')
                break;
        }
    }
}
